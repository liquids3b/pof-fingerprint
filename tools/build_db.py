"""Build or extend the fingerprint database from your own labelled captures.

The shipped database is a starting point. Real accuracy comes from your own
traffic: capture SYNs on the VPS with an OS you know, then turn them into
entries here.

    # one capture per known OS, appended to a new table
    python tools/build_db.py --read win10.pcap --label Windows \\
                            --read ubuntu.pcap --label Linux \\
                            --out database/mine.json

    # keep adding to it later (weights are summed, not overwritten)
    python tools/build_db.py --read ubuntu2.pcap --label Linux \\
                            --out database/mine.json --merge

    # how well does the current table explain a capture?
    python tools/build_db.py --read unknown.pcap --report

Capture with something like:  tcpdump -i eth0 -w win10.pcap 'tcp[tcpflags] & tcp-syn != 0'
"""
import argparse
import json
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'src'))

import database   # noqa: E402
import packet     # noqa: E402
import pcap       # noqa: E402

# The fields a database entry may carry, in output order.
SCORED_FIELDS = ('tcp_options', 'tcp_data_offset', 'ip_total_length', 'ip_ttl_initial',
                 'tcp_window_size', 'tcp_window_scaling', 'tcp_mss', 'ip_id_zero',
                 'tcp_timestamp', 'tcp_timestamp_echo', 'ip_tos', 'tcp_flags')


def parse_args(argv=None):
    parser = argparse.ArgumentParser(prog='build_db.py', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--read', action='append', default=[], metavar='FILE.pcap',
                        help='capture file to learn from (repeatable)')
    parser.add_argument('--label', action='append', default=[], metavar='OS',
                        help='label for the matching --read (repeatable, in order)')
    parser.add_argument('--out', metavar='FILE.json', help='write the table here')
    parser.add_argument('--merge', action='store_true',
                        help='merge into an existing --out instead of replacing it')
    parser.add_argument('--min-count', type=int, default=1,
                        help='drop profiles seen fewer than this many times')
    parser.add_argument('--report', action='store_true',
                        help='classify the captures with the current table and print the result')
    parser.add_argument('--database', default=str(database.DEFAULT_DATABASE),
                        help='table used by --report')
    return parser.parse_args(argv)


def entry_key(entry):
    return (entry.get('os'),) + tuple(entry.get(field) for field in SCORED_FIELDS)


def entry_from(fingerprint, label, count):
    values = database.features(fingerprint)
    entry = OrderedDict()
    entry['os'] = label
    entry['n'] = count
    for field in SCORED_FIELDS:
        entry[field] = values.get(field)
    entry['tcp_options_ordered'] = values.get('tcp_options_ordered')
    entry['note'] = 'learned from your own capture'
    return entry


def learn(captures, labels, min_count):
    """Group SYNs by their exact fingerprint shape; returns `{key: entry}`."""
    entries = OrderedDict()
    for path, label in zip(captures, labels):
        fingerprints, _skipped = read_fingerprints(path)
        for fingerprint in fingerprints:
            entry = entry_from(fingerprint, label, 1)
            key = entry_key(entry)
            if key in entries:
                entries[key]['n'] += 1
            else:
                entries[key] = entry
    return {key: entry for key, entry in entries.items() if entry['n'] >= min_count}


def read_fingerprints(path):
    """Client SYNs of one capture file, decoded with the live code path."""
    fingerprints, skipped = [], 0
    for timestamp, linktype, data in pcap.frames(path):
        frame = pcap.to_ethernet(data, linktype)
        if frame is None:
            skipped += 1
            continue
        fingerprint = packet.decode_frame(frame, timestamp)
        if fingerprint is None or not packet.is_client_syn(fingerprint):
            continue
        fingerprint['ip_src'] = packet.normalize_ip(fingerprint['ip_src'])
        fingerprints.append(fingerprint)
    return fingerprints, skipped


def load_entries(path):
    document = json.loads(Path(path).read_text(encoding='utf-8'))
    entries = document.get('entries') if isinstance(document, dict) else document
    return list(entries or [])


def save_entries(path, entries, origin=None):
    """Write the table back in the documented format, heaviest profiles first."""
    document = OrderedDict()
    document['format'] = database.DB_FORMAT
    document['origin'] = origin or 'generated by tools/build_db.py from own captures'
    document['how_to_tune'] = ('entries are weighted by n (sessions); learn from your own '
                               'captures with tools/build_db.py, or convert a foreign table '
                               'with tools/import_db.py - see README.md')
    try:  # keep the field documentation of the shipped table if it is around
        shipped = json.loads(database.DEFAULT_DATABASE.read_text(encoding='utf-8'))
        for key in ('field_help',):
            if key in shipped:
                document[key] = shipped[key]
    except (OSError, ValueError):
        pass
    document['entries'] = sorted(entries, key=lambda item: (item.get('os') or '', -item.get('n', 1)))
    Path(path).write_text(json.dumps(document, indent=2) + '\n', encoding='utf-8')


def merge(existing, learned, sum_weights=True):
    """Fold `learned` into `existing`; identical profiles share one entry.

    `sum_weights` is what `build_db.py --merge` wants (another capture of the
    same stack adds sessions). An importer passes `False`: re-importing the
    same table must leave the entry exactly as it was.
    """
    merged = OrderedDict()
    for entry in existing:
        merged[entry_key(entry)] = dict(entry)
    added = 0
    for key, entry in learned.items():
        if key in merged:
            if sum_weights:
                merged[key]['n'] = merged[key].get('n', 1) + entry['n']
        else:
            merged[key] = entry
            added += 1
    return list(merged.values()), added


def report(capture_paths, db):
    """Print how the current table explains each capture file."""
    for path in capture_paths:
        fingerprints, skipped = read_fingerprints(path)
        print('{}: {} client SYNs ({} records skipped)'.format(path, len(fingerprints), skipped))
        counts, confidences = {}, []
        for fingerprint in fingerprints:
            result = db.classify(fingerprint)
            name = result['os'] or 'unknown'
            counts[name] = counts.get(name, 0) + 1
            confidences.append(result['confidence'])
        total = max(1, len(fingerprints))
        for name, count in sorted(counts.items(), key=lambda item: -item[1]):
            print('   {:<12} {:>6.1f}%  ({} SYNs)'.format(
                name, 100.0 * count / total, count))
        if confidences:
            print('   mean confidence: {:.3f}'.format(sum(confidences) / len(confidences)))


def main(argv=None):
    args = parse_args(argv)
    if len(args.label) not in (0, len(args.read)):
        print('build_db: --label must be given once per --read', file=sys.stderr)
        return 2
    if not args.read:
        print('build_db: nothing to do, pass at least one --read FILE.pcap', file=sys.stderr)
        return 2
    labels = args.label or ['Unknown'] * len(args.read)

    if args.report:
        report(args.read, database.Database(args.database).load())
        return 0

    learned = learn(args.read, labels, args.min_count)
    if not learned:
        print('build_db: no client SYNs found, is this a capture of incoming traffic?')
        return 1

    entries = list(learned.values())
    if args.merge and args.out and Path(args.out).exists():
        entries, added = merge(load_entries(args.out), learned)
        print('merged: {} profiles, {} new'.format(len(entries), added))
    for key in sorted(learned, key=lambda item: -learned[item]['n']):
        entry = learned[key]
        print('{:>7}  {:<12} ttl={:<4} len={:<4} win={:<6} ws={:<4} mss={:<5} tos={} flags={:#04x}  {}'.format(
            entry['n'], entry['os'], entry['ip_ttl_initial'], entry['ip_total_length'],
            entry['tcp_window_size'], entry['tcp_window_scaling'], entry['tcp_mss'],
            entry['ip_tos'], entry['tcp_flags'] or 0, entry['tcp_options']))

    if args.out:
        save_entries(args.out, entries)
        print('wrote {} entries to {}'.format(len(entries), args.out))
    else:
        print(json.dumps({'format': database.DB_FORMAT, 'entries': entries}, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
